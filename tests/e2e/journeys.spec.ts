import { test, expect, type BrowserContext, type Page } from '@playwright/test'
const headers = { 'X-SkillSync-Client': 'web' }
async function account(context: BrowserContext, name: string, role = 'student') {
  const email = `${name.toLowerCase()}-${Date.now()}@example.com`
  const response = await context.request.post('/api/auth/signup', { headers, data: { firstName: name, lastName: 'Tester', email, password: 'StrongPass123', role, agreeToTerms: true } })
  expect(response.status()).toBe(201)
  return (await response.json()).data
}
async function nav(page: Page, name: string) {
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name, exact: true }).click()
}

