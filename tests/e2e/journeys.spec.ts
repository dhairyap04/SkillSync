test('mobile navigation opens every new feature without horizontal overflow', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    await account(context, 'Mobile')
    const page = await context.newPage()
    await page.goto('/dashboard')
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
    await nav(page, 'Career roadmaps')
    await expect(page.getByRole('heading', { name: 'Career roadmaps', exact: true })).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Main navigation' })).toHaveCount(0)
    for (const path of ['skills', 'goals', 'roadmaps', 'matches', 'mentorships', 'challenges', 'passport', 'exchanges', 'reports', 'messages', 'resources']) {
      await page.goto('/dashboard/' + path)
      await expect(page.locator('h1')).toBeVisible()
      await expect(page.getByRole('alert')).toHaveCount(0)
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
      expect(overflow, `horizontal overflow on ${path}`).toBe(false)
    }
  } finally { await context.close() }
})

test('failed milestone writes show an error and restore the saved state', async ({ browser }) => {
  const context = await browser.newContext()
  try {
    await account(context, 'Recovery')
    const result = await context.request.post('/api/roadmaps', { headers, data: { templateId: 'frontend' } })
    expect(result.status()).toBe(201)
    const page = await context.newPage()
    await page.goto('/dashboard/goals')
    await page.route('**/api/goals/*', async route => {
      if (route.request().method() === 'PUT') await route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ success: false, message: 'Simulated save failure' }) })
      else await route.continue()
    })
    const milestone = page.getByRole('checkbox', { name: 'Build a responsive page', exact: true })
    await milestone.click()
    await expect(page.getByText('Simulated save failure', { exact: true })).toBeVisible()
    await expect(milestone).not.toBeChecked()
    await page.unroute('**/api/goals/*')
    await milestone.check()
    await expect(page.getByText('50% complete', { exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('checkbox', { name: 'Build a responsive page', exact: true })).toBeChecked()
  } finally { await context.close() }
})

